"""Leaderboard: one backend × metric table per (date, dataset, judge, reader).

Built only from committed result dirs (`results/<date>/<dataset>/<backend>/`,
see `core.publish`). Rows of different judge models, judge prompt versions or
readers never share a table, since their judge metrics are not comparable.
Each cell is the value, its 95% CI and n (`†` marks n below the reporting
minimum). A metric that is null for every row (e.g. judge metrics on a run
without a judge) is left out, not shown as zero. Judge metric headers carry the
judge's validation status; `oracle` is labelled an upper bound, and
vendor-tuned configs get their own labelled row. Output is deterministic, so
CI can re-derive it and diff.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from membench.core.report.markdown import (
    _JUDGE_NOTE,
    _METRICS,
    _fmt_ci,
    _fmt_value,
    _stat,
)
from membench.core.stats import MIN_HEADLINE_N
from membench.core.validation import JUDGE_METRICS
from membench.core.validation.status import report_metric_status

_LOWER_IS_BETTER = {"staleness", "contradiction_rate"}
_QUALITY = [(k, label) for k, label, kind in _METRICS if kind == "ratio" and k != "error_rate"]
_UPPER_BOUND = {"oracle": "upper bound: sees each query's evidence"}


def collect(results: Path) -> list[dict]:
    """Every published result under `results/` as {path, report, meta}, sorted by path."""
    entries = []
    for path in sorted(results.glob("*/*/*/report.json")):
        meta_path = path.parent / "meta.json"
        meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
        entries.append({"path": path, "report": json.loads(path.read_text()), "meta": meta})
    return entries


def _group(entry: dict) -> tuple[str, str, str, str]:
    manifest = entry["report"]["manifest"]
    judge, reader = manifest.get("judge"), manifest.get("reader")
    date, dataset = entry["path"].parts[-4:-2]
    return (
        date,
        dataset,
        f"{judge['model']} (prompt v{judge['prompt_version']})" if judge else "none",
        f"{reader['model']} (prompt v{reader['prompt_version']})" if reader else "none",
    )


def _row_label(entry: dict) -> str:
    backend = entry["report"]["manifest"]["backend"]["name"]
    config = entry["meta"].get("config", "default")
    label = backend if config == "default" else f"{backend} ({config})"
    if backend in _UPPER_BOUND:
        label += " *(upper bound)*"
    return label


def _cell(report: dict, key: str) -> str:
    value = report["scores"].get(key)
    if value is None:
        return "n/a"
    stat = _stat(report, key)
    parts = [_fmt_value("ratio", value), _fmt_ci("ratio", stat)]
    if stat:
        parts.append(f"n={stat['n']}" + ("†" if stat.get("indicative") else ""))
    return " ".join(p for p in parts if p)


def _number(value: object, fmt: str) -> str:
    return "n/a" if value is None else fmt.format(value)


def render_leaderboard(entries: list[dict], base: Path) -> str:
    """Markdown leaderboard; report links are relative to `base` (the output's dir)."""
    lines = [
        "# MemBench results",
        "",
        ("<!-- Generated by `membench leaderboard results/ --out results/README.md`; "
         "do not edit. -->"),
        "",
        ("Every row links to its committed `report.json`; re-score any of them offline with "
         "`membench rescore --in <report.json> --judge-cache <dir>/judge_cache.json --check`."),
        "",
    ]
    if not entries:
        return "\n".join([*lines, "_No published results._", ""])
    groups: dict[tuple[str, str, str, str], list[dict]] = {}
    for entry in entries:
        groups.setdefault(_group(entry), []).append(entry)
    for (date, dataset, judge, reader), rows in sorted(groups.items()):
        rows.sort(key=lambda e: (e["report"]["manifest"]["backend"]["name"] in _UPPER_BOUND,
                                 _row_label(e)))
        lines += _table(date, dataset, judge, reader, rows, base)
    notes = [f"`{name}`: {why}" for name, why in _UPPER_BOUND.items()]
    lines += [
        "## Notes",
        "",
        ("- Cells: value [95% CI] n=… ; † = n below the reporting minimum "
         f"({MIN_HEADLINE_N} queries), indicative only. ↓ = lower is better."),
        ("- Rows of different judge models, judge prompt versions or readers are never "
         "in the same table."),
        ("- " + "; ".join(notes) + ". `(vendor-tuned)` rows use the vendor's recommended "
         "config (configs/vendor-tuned/); other rows use the defaults (configs/default/)."),
        ("- USD / 1k queries counts judge, reader and backend LLM spend at the dated price "
         "table; offline backends without a judge or reader cost $0."),
        "- Recall p95 is n/a below 100 recall samples.",
        f"- {_JUDGE_NOTE}",
        "",
    ]
    return "\n".join(lines)


def _table(date: str, dataset: str, judge: str, reader: str, rows: list[dict],
           base: Path) -> list[str]:
    reports = [e["report"] for e in rows]
    metrics = [(k, label) for k, label in _QUALITY
               if any(r["scores"].get(k) is not None for r in reports)]
    headers = ["Backend"]
    for key, label in metrics:
        header = label + (" ↓" if key in _LOWER_IS_BETTER else "")
        if key in JUDGE_METRICS:
            header += f" ({report_metric_status(reports[0], key)})"
        headers.append(header)
    headers += ["Tokens / query", "Recall p95 (ms)", "USD / 1k queries", "Error rate",
                "Valid", "Report"]
    lines = [
        f"## {dataset} — {date}",
        "",
        f"Judge: {judge}. Reader: {reader}. Queries: {_queries(reports[0])}.",
        "",
        "| " + " | ".join(headers) + " |",
        "|" + " --- |" * len(headers),
    ]
    for entry, report in zip(rows, reports):
        scores, cost = report["scores"], report.get("cost") or {}
        link = Path(os.path.relpath(entry["path"], base)).as_posix()
        cells = [_row_label(entry), *(_cell(report, k) for k, _ in metrics)]
        cells += [
            _number(scores.get("token_cost"), "{:.1f}"),
            _number(scores.get("recall_p95_ms"), "{:.2f}"),
            _number(cost.get("usd_per_1k_queries"), "${:.2f}"),
            _number(scores.get("error_rate"), "{:.1%}"),
            "yes" if report.get("valid", True) else "no",
            f"[report.json]({link})",
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return [*lines, ""]


def _queries(report: dict) -> int:
    return sum(1 for t in report["traces"] if t["step_type"] == "query")
